// Tables returns the tables by language, for tests.
func Tables() map[Lang]Table { return map[Lang]Table{ZH: zh, EN: en} }

// OnEmptyArg, when set (tests), hears every placeholder filled with an empty
// string: "这是  上的浏览器" must fail a test, not reach a person.
var OnEmptyArg func(key string, arg int)

// usedArgs says which of n arguments a format's verbs print (%s in order,
// %[2]s by position; %% prints none).
func usedArgs(format string, n int) []bool {
	used := make([]bool, n)
	next := 0
	for i := 0; i < len(format); i++ {
		if format[i] != '%' {
			continue
		}
		i++
		if i < len(format) && format[i] == '%' {
			continue
		}
		if i < len(format) && format[i] == '[' {
			j := strings.IndexByte(format[i:], ']')
			if j > 0 {
				if p, err := strconv.Atoi(format[i+1 : i+j]); err == nil {
					next = p - 1
				}
				i += j
			}
		}
		if next >= 0 && next < n {
			used[next] = true
		}
		next++
	}
	return used
}

// Strings translates keys in one language.
type Strings struct {
	Lang  Lang
	table Table
}

// New returns the strings of a language (English for an unknown one).
func New(l Lang) *Strings {
	if l == ZH {
		return &Strings{Lang: ZH, table: zh}
	}
	return &Strings{Lang: EN, table: en}
}

// T translates key, formatting args into it. A missing key shows itself,
// so it is seen and fixed.
func (s *Strings) T(key string, args ...any) string {
	v, ok := s.table[key]
	if !ok {
		if v, ok = en[key]; !ok {
			return key
		}
	}
	if len(args) == 0 {
		return v
	}
	if OnEmptyArg != nil {
		used := usedArgs(v, len(args))
		for i, a := range args {
			if s, ok := a.(string); ok && used[i] && strings.TrimSpace(s) == "" {
				OnEmptyArg(key, i)
			}
		}
	}
	out := fmt.Sprintf(v, args...)
	if s.Lang == ZH {
		out = JoinHan(SpaceHan(out))
	}
	return out
}

// SpaceHan puts a space where a Chinese character touches a Latin letter
// or a digit (D78): a name or a number filled into zh copy ("住在%s 上"
// with "hel") never runs into the words round it.
func SpaceHan(s string) string {
	rs := []rune(s)
	out := make([]rune, 0, len(rs)+4)
	latin := func(r rune) bool { return r < 0x250 && (unicode.IsLetter(r) || unicode.IsDigit(r)) }
	for i, r := range rs {
		if i > 0 {
			p := rs[i-1]
			if unicode.Is(unicode.Han, p) && latin(r) || latin(p) && unicode.Is(unicode.Han, r) {
				out = append(out, ' ')
			}
		}
		out = append(out, r)
	}
	return string(out)
}

// JoinHan drops a space between two Chinese characters: zh copy spaces
// around a name ("%s 刚做完一件事") so a Latin name reads well, and a
// Chinese name ("小鸭") must then sit flush.
func JoinHan(s string) string {
	rs := []rune(s)
	out := rs[:0:0]
	for i, r := range rs {
		if r == ' ' && i > 0 && i+1 < len(rs) && unicode.Is(unicode.Han, rs[i-1]) && unicode.Is(unicode.Han, rs[i+1]) {
			continue
		}
		out = append(out, r)
	}
	return string(out)
}

// Detect picks the language: DUCTER_LOCALE, else the system's preferred
// languages (as mygo reports them), else LANG, else English.
func Detect(preferred []string) Lang {
	if l := os.Getenv("DUCTER_LOCALE"); l != "" {
		return parse(l)
	}
	for _, p := range preferred {
		if l := parse(p); l != "" {
			return l
		}
	}
	if l := parse(os.Getenv("LANG")); l != "" {
		return l
	}
	return EN
}

// Fixed reports whether DUCTER_LOCALE pins the language.
func Fixed() bool { return os.Getenv("DUCTER_LOCALE") != "" }

// FromText guesses the language a person writes in: Chinese with any Han
// character, English with Latin words and none, else "".
func FromText(text string) Lang {
	latin := 0
	for _, r := range text {
		switch {
		case unicode.Is(unicode.Han, r):
			return ZH
		case r < 0x80 && unicode.IsLetter(r):
			latin++
		}
	}
	if latin >= 3 {
		return EN
	}
	return ""
}

func parse(tag string) Lang {
	tag = strings.ToLower(tag)
	switch {
	case strings.HasPrefix(tag, "zh"):
		return ZH
	case strings.HasPrefix(tag, "en"):
		return EN
	}
	return ""
}
