func init() {
	for k, v := range zhSetFind {
		zh[k] = v
	}
	for k, v := range enSetFind {
		en[k] = v
	}
}

// SetFindBoth is a key's words in both languages, for matching whatever the window speaks.
func SetFindBoth(key string) []string {
	var out []string
	for _, t := range []Table{zh, en} {
		if v, ok := t[key]; ok && v != "" {
			out = append(out, v)
		}
	}
	return out
}
