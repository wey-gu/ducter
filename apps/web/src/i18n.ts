export const TABLES: Record<Lang, Record<string, string>> = { zh, en };

/** Drops a space between two Chinese characters (zh copy spaces around a name for Latin names). */
export function joinHan(s: string): string {
  return s.replace(/(\p{Script=Han}) (?=\p{Script=Han})/gu, "$1");
}

/** printf-like: %s and %d in order, %[n]s by position (1-based). */
export function format(fmt: string, args: unknown[]): string {
  let i = 0;
  return fmt.replace(/%(?:\[(\d+)\])?([sd%])/g, (_m, pos: string | undefined, verb: string) => {
    if (verb === "%") return "%";
    const v = pos ? args[Number(pos) - 1] : args[i++];
    return String(v ?? "");
  });
}

export interface Strings {
  lang: Lang;
  t(key: string, ...args: unknown[]): string;
}

export function strings(lang: Lang): Strings {
  const table = TABLES[lang];
  return {
    lang,
    t(key, ...args) {
      const v = table[key] ?? en[key] ?? key; // a missing key shows itself, so it gets fixed
      if (!args.length) return v;
      const out = format(v, args);
      return lang === "zh" ? joinHan(out) : out;
    },
  };
}

export function detectLang(langs: readonly string[] = (typeof navigator !== "undefined" && navigator.languages) || []): Lang {
  for (const l of langs) {
    const s = l.toLowerCase();
    if (s.startsWith("zh")) return "zh";
    if (s.startsWith("en")) return "en";
  }
  return "en";
}

/** The language a person writes in: zh with any Han character, en with 3+ Latin letters and none. */
export function langOfText(text: string): Lang | "" {
  if (/\p{Script=Han}/u.test(text)) return "zh";
  return (text.match(/[A-Za-z]/g)?.length ?? 0) >= 3 ? "en" : "";
}
